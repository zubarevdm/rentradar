"""Текстовые сигналы по описанию объявления: риелтор / увод общения с площадки.

Чистые функции без сети — используются и в фрод-фильтре (скоринг), и в матчинге
персонального фильтра. Терпимы к обфускации (латиница вместо кириллицы, разделители
между буквами) — ей пользуются все, кто обходит бан площадок.
"""

from __future__ import annotations

import re

# ── риелторские фразы ────────────────────────────────────────────────────
_AGENT_MARKERS = (
    "агентств",
    "риелтор",
    "риэлтор",
    "большая база",
    "своя база",
    "актуальная база",
    "база квартир",
    "база вариант",
    "подберем вариант",
    "подберём вариант",
    "поможем подобрать",
    "поможем найти",
    "поможем с подбором",
)


def looks_like_agent(description: str | None) -> bool:
    """Похоже ли описание на риелторское (по характерным фразам). Авито-описания
    часто обфусцированы латиницей («бaза квapтир») — де-обфусцируем как и скам."""
    if not description:
        return False
    text = description.lower().replace("ё", "е").translate(_CONFUSABLE)
    return any(marker.replace("ё", "е") in text for marker in _AGENT_MARKERS)


# ── увод общения с площадки ──────────────────────────────────────────────
# Латинские двойники кириллицы (обфускация «соBСтвeнник» → «собственник»).
_CONFUSABLE = str.maketrans(
    {
        "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
        "k": "к", "m": "м", "t": "т", "h": "н", "b": "в", "r": "г", "n": "п",
    }
)
_OFFPLATFORM_MARKERS = (
    "телеграм", "телега", "телеге", "тлеграм", "тлг", "тгк", "тгканал", "телеграмм",
    "вотсап", "ватсап", "вацап", "воцап", "вайбер", "whatsapp", "telegram", "viber",
    "втг", "влс", "вличку", "вдирект", "напишитемне", "пишитемне",
    "внеавито", "мимоавито", "нечерезавито", "tme", "wame", "tgk", "tlk", "тлк",
)


def solicits_offplatform(text: str | None) -> bool:
    """Уводит ли объявление общение с площадки (телеграм/вотсап/телефон/@ник).
    Режем всех — легитимные «пишите в тг» тоже обходят бан площадки обфускацией, а
    нам важнее чистый канал без мошенников, чем пара таких квартир."""
    if not text:
        return False
    low = text.lower().replace("ё", "е")
    sep = r"[\s.\-_/|·•]+"
    # Проверяем и оригинал (ловит чистую латиницу telegram/whatsapp), и
    # де-обфусцированное (ловит смешанные кириллица+латиница). «т г к» → «тгк».
    compact_orig = re.sub(sep, "", low)
    compact_deob = re.sub(sep, "", low.translate(_CONFUSABLE))
    if any(m in compact_orig or m in compact_deob for m in _OFFPLATFORM_MARKERS):
        return True
    if re.search(r"@[a-zа-я0-9_]{4,}", low):  # @username
        return True
    digits = re.sub(r"\D", "", low)  # телефон: +7/8 + 10 цифр
    return bool(re.search(r"(?:\+?7|8)\d{10}", digits))
