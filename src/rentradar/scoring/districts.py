# Грубый штраф за Новую Москву (НАО/ТАО) — далеко от центра.
_NEW_MOSCOW_MARKERS = ("нао", "тао", "новомосковск", "троицк", "щербинк")


def district_weight(city: str, district: str | None) -> float | None:
    """Вес престижности района в [0..1], либо None если город/район неизвестны."""
    if district is None or city.strip().lower() not in {"москва"}:
        return None
    norm = _normalize_text(district)
    if norm in _MOSCOW:
        return _MOSCOW[norm]
    if any(marker in norm for marker in _NEW_MOSCOW_MARKERS):
        return 0.35
    return 0.5  # неизвестный московский район — нейтрально
